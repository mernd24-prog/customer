import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync(new URL('../src/api/deals.js', import.meta.url), 'utf8');
const start = source.indexOf('const pendingDealProductRequests');
const end = source.indexOf('\n/**', start);
let calls = 0;
let resolve;
let reject;
const context = { endpoints: { deals: { publicProducts: '/api/v1/deals/public/products' } }, api: { get(url, config) {
  calls++;
  assert.equal(url, '/api/v1/deals/public/products');
  assert.equal(config.params.sort, 'ending_soon');
  assert.equal(config.params.attr_color, 'Blue');
  return new Promise((yes, no) => { resolve = yes; reject = no; });
} } };
vm.createContext(context);
vm.runInContext(source.slice(start, end).replace('export const getPublicDealProducts', 'globalThis.getPublicDealProducts'), context);
const params = { page: 1, limit: 10, sort: 'ending_soon', attr_color: 'Blue' };
const requests = [context.getPublicDealProducts(params), context.getPublicDealProducts(params)];
assert.equal(calls, 1, 'simultaneous page requests share the API request');
resolve({ data: { success: true, data: [] } });
await Promise.all(requests);
const failed = context.getPublicDealProducts(params);
assert.equal(calls, 2, 'subsequent visits can fetch fresh data');
reject(new Error('timeout'));
await assert.rejects(failed, /timeout/);
const retry = context.getPublicDealProducts(params);
assert.equal(calls, 3, 'failure must not block a retry');
resolve({ data: { success: true, data: [] } });
await retry;
console.log('PASS: Deals mount requests deduplicate, forward filters and recover after failure.');
